/** Parses "اسم المنتج = رقم" lines into {name, sku, quantity} rows, splitting a trailing "(Sxx)" off the name into its own SKU field — same convention real-catalog.js already uses for these 9 products. */
export function parseRealStockList(rawText = RAW_STOCK_TEXT) {
  const rows = [];
  for (const rawLine of rawText.split('\n')) {
    const line = rawLine.trim();
    if (!line) continue;
    const eqIdx = line.lastIndexOf('=');
    if (eqIdx === -1) continue;
    const namePart = line.slice(0, eqIdx).trim();
    const qtyPart = line.slice(eqIdx + 1).trim();
    const quantity = Number(qtyPart);
    if (Number.isNaN(quantity)) continue;

    const skuMatch = namePart.match(/\s*\((S\d+)\)\s*$/);
    const name = skuMatch ? namePart.slice(0, skuMatch.index).trim() : namePart;
    const sku = skuMatch ? skuMatch[1] : '';

    rows.push({ name, sku, quantity });
  }
  return rows;
}
